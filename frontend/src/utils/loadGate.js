// ------------------------------------------------------------------
// 加载序列闸：每次加载取一个递增令牌，只有持最后一次令牌的响应允许落地。
// 值班员连续快速操作 / 刷新时，较早发出的慢响应不得覆盖最新状态。
// 抽成独立模块：IntakeView 与 PressView 共用同一份口径。
// ------------------------------------------------------------------

export function createLoadGate() {
  let seq = 0
  return {
    next() { return ++seq },
    isCurrent(token) { return token === seq }
  }
}
